// Generates scripts/procurement/build_tools_payload.cjs — a single-file, dependency-free copy of the
// procurement normalizer + import plan, for the daily Odoo sync (it runs in the scheduled task's cloud workspace).
// Run after changing src/lib/procurement/{types,normalize,payload}.ts:  npm run build:sync-bundle
// tests/procurement-sync.test.cjs fails when the committed bundle is out of date.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const root = path.join(__dirname, '..', '..');
const MODULES = ['types', 'normalize', 'payload'];

function compile(name) {
  const src = fs.readFileSync(path.join(root, 'src/lib/procurement', `${name}.ts`), 'utf8');
  return ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, removeComments: false } }).outputText;
}

function bundle() {
  const mods = MODULES.map(n => `  ${JSON.stringify('./' + n)}: function (module, exports, require) {\n${compile(n).replace(/^/gm, '    ')}\n  },`).join('\n');
  return `#!/usr/bin/env node
// GENERATED by scripts/procurement/bundle-sync.cjs from src/lib/procurement/{${MODULES.join(',')}}.ts — do not edit by hand.
//
// Daily-sync payload builder for tools.eashe.org/procurement.
// Usage: node build_tools_payload.cjs <odoosync_data.json> <odoosync_polines.json> <outdir> [quotes_extracted.json]
// Writes <outdir>/NNN_<table>.json (one upsert request each), <outdir>/finalize.json and <outdir>/manifest.json
// (file names + SHA-256), which push_tools.ps1 posts in order with a single-use import ticket.
// Without a quotations file the existing quotations on the site are left untouched.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const __defs = {
${mods}
};
const __cache = {};
function __require(name) {
  if (__cache[name]) return __cache[name].exports;
  if (!__defs[name]) throw new Error('unknown module ' + name);
  const module = { exports: {} };
  __cache[name] = module;
  __defs[name](module, module.exports, __require);
  return module.exports;
}

function readJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8').replace(/^\\uFEFF/, ''));
}

function main(argv) {
  const [syncPath, poPath, outDir, quotesPath] = argv;
  if (!syncPath || !poPath || !outDir) {
    console.error('usage: node build_tools_payload.cjs <odoosync_data.json> <odoosync_polines.json> <outdir> [quotes_extracted.json]');
    process.exit(2);
  }
  const { normalizeSync } = __require('./normalize');
  const { importPlan } = __require('./payload');
  const sync = readJson(syncPath);
  const po = readJson(poPath);
  const quotes = quotesPath ? readJson(quotesPath) : null;
  if (!sync || typeof sync !== 'object' || !Object.values(sync).every(v => v && Array.isArray(v.prs))) throw new Error('PR file is not pull.js output');
  if (!Array.isArray(po)) throw new Error('PO line file must be an array');
  if (quotes && (!Array.isArray(quotes.quotes) || !Array.isArray(quotes.items))) throw new Error('quotation file has no quotes/items');
  const rows = normalizeSync(sync, po, quotes);
  if (!rows.proc_pr.length) throw new Error('no PRs in the PR file — refusing to build an empty snapshot');
  if (!rows.proc_po_lines.length) throw new Error('no PO lines matched the PRs — check that the PO line file comes from the same pull');
  const source = 'daily-sync: ' + [syncPath, poPath, quotesPath].filter(Boolean).map(p => path.basename(p)).join(', ');
  const { tables, upserts, finalize } = importPlan(rows, !!quotes, source);
  fs.mkdirSync(outDir, { recursive: true });
  const write = (name, body) => {
    const text = JSON.stringify(body);
    fs.writeFileSync(path.join(outDir, name), text, 'utf8');
    return crypto.createHash('sha256').update(text, 'utf8').digest('hex');
  };
  const files = upserts.map((b, i) => {
    const name = String(i + 1).padStart(3, '0') + '_' + b.table + '.json';
    return { name, table: b.table, rows: b.rows.length, sha256: write(name, b) };
  });
  const fin = { name: 'finalize.json', sha256: write('finalize.json', finalize) };
  const counts = Object.fromEntries(tables.map(t => [t, rows[t].length]));
  const manifest = { created_at: new Date().toISOString(), source, counts, files, finalize: fin };
  fs.writeFileSync(path.join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 1), 'utf8');
  console.log(JSON.stringify({ ok: true, counts, requests: files.length + 1 }));
}

if (require.main === module) {
  try { main(process.argv.slice(2)); } catch (e) { console.error('ERROR ' + (e && e.message ? e.message : e)); process.exit(1); }
}
module.exports = { require: __require, main };
`;
}

const out = path.join(__dirname, 'build_tools_payload.cjs');
if (require.main === module) {
  fs.writeFileSync(out, bundle(), 'utf8');
  console.log('wrote', path.relative(root, out));
}
module.exports = { bundle, out };
