const idx = (code: StorageClassCode) => STORAGE_CLASS_ORDER.indexOf(code);

/** ผลการจับคู่ 2 ประเภท */
export function compat(a: StorageClassCode, b: StorageClassCode): CompatCell {
  const i = idx(a), j = idx(b);
  if (i < 0 || j < 0) return '-';
  return M[i][j];
}

export const COMPAT_MATRIX = M;

/** ใช้ใน dev/test: ตารางต้องสมมาตร (a,b) === (b,a) */
export function assertMatrixSymmetric(): string[] {
  const errs: string[] = [];
  for (let i = 0; i < M.length; i++) {
    if (M[i].length !== STORAGE_CLASS_ORDER.length) errs.push(`row ${STORAGE_CLASS_ORDER[i]} has ${M[i].length} cells`);
    for (let j = 0; j < i; j++) {
      if (M[i][j] !== M[j][i]) errs.push(`${STORAGE_CLASS_ORDER[i]}×${STORAGE_CLASS_ORDER[j]}: ${M[i][j]} vs ${M[j][i]}`);
    }
  }
  return errs;
}

