test('composition API validates data and preserves ownership, omitted fields and optimistic concurrency',async({request})=>{
 await login(request);
 const create=await request.post('/api/chemical/substances',{data:{company_id:'amt',name:'Mixture API test',product_type:'mixture',components}});
 expect(create.status(),await create.text()).toBe(201);
 const row=(await create.json()).data;
 const patch=await request.put('/api/chemical/substances/'+row.id,{data:{name:'Renamed',expected_updated_at:row.updated_at}});
 expect(patch.status(),await patch.text()).toBe(200);
 const updated=(await patch.json()).data;expect(updated.components).toEqual(components);
 expect((await request.put('/api/chemical/substances/'+row.id,{data:{components:[],expected_updated_at:row.updated_at}})).status()).toBe(409);
 for(const body of [{components:[{...components[0],cas_no:'7697-37-1'}]},{product_type:'invented'},{components:'json-string'}]) expect((await request.put('/api/chemical/substances/'+row.id,{data:{...body,expected_updated_at:updated.updated_at}})).status()).toBe(400);
 expect((await request.get('/api/chemical/legal?company_id=aab&substance_id='+row.id)).status()).toBe(403);
 expect((await request.get('/api/chemical/legal?company_id=amt&substance_id=44444444-4444-4444-8444-444444444444')).status()).toBe(404);
 const detail=await(await request.get('/api/chemical/legal?company_id=amt&substance_id='+row.id)).json();
 expect(detail.check).toBeNull();expect(detail.composition.checked_cas_count).toBe(5);expect(detail.identityWarning).toBeNull();
});
