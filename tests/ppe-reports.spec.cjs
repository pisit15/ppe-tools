const {test,expect}=require('@playwright/test');
const ExcelJS=require('exceljs');
const {product}=require('./ppe-requests-fixture.cjs');
const dept='ฝ่ายผลิตและประกอบอุปกรณ์ป้องกันอันตราย ชื่อแผนกฉบับเต็ม';
async function login(context) { const res=await context.request.post('/api/auth/login',{data:{username:'manager-amt',password:'local-test-password'}});expect(res.status()).toBe(200); }
test('report API retrieves all pages, enforces company boundaries and validates month ranges',async({context,browser})=>{
  await login(context);
  const res=await context.request.get('/api/ppe/reports?company_id=amt&from=2026-10&to=2026-10');
  expect(res.status(),await res.text()).toBe(200);
  const data=await res.json();
  expect(data.transactions.filter(t=>t.product_id===product&&t.transaction_date==='2026-10-01')).toHaveLength(2105);
  expect(data.transactions.every(t=>t.company_id==='amt'&&t.transaction_date>='2026-09-01'&&t.transaction_date<='2026-10-31')).toBe(true);
  expect(data.transactions.some(t=>t.ppe_products?.name==='แว่นตานิรภัย สีใส')).toBe(true);
  for(const company of ['aab','all']) expect((await context.request.get(`/api/ppe/reports?company_id=${company}&from=2026-10&to=2026-10`)).status()).toBe(403);
  expect((await context.request.get('/api/ppe/reports?company_id=amt&from=2026-13&to=2026-13')).status()).toBe(400);
  const anonymous=await browser.newContext();
  expect((await anonymous.request.get('http://127.0.0.1:4327/api/ppe/reports?company_id=amt&from=2026-10&to=2026-10')).status()).toBe(401);
  await anonymous.close();
});
test('complete drilldown, month filtering and Excel match on desktop and mobile',async({page,context})=>{
  await login(context);
  await page.clock.setFixedTime(new Date('2026-10-26T06:00:00Z'));
  await page.goto('/ppe/reports?company_id=amt');
  let section=page.locator('section[aria-labelledby="usage-report-heading"]');
  await expect(section.getByRole('heading',{name:'วิเคราะห์การเบิก'})).toBeVisible();
  await page.getByRole('button',{name:'เลือกช่วงเดือนรายงาน'}).click();
  await page.getByRole('button',{name:'เดือนนี้',exact:true}).click();
  await expect(section.getByText(/ตุลาคม 2569/)).toBeVisible();
  await section.getByRole('button',{name:new RegExp('^'+dept)}).click();
  await expect(section.locator('tbody tr')).toHaveCount(15);
  await expect(section.getByRole('cell',{name:/รุ่น 12/})).toBeVisible();
  await expect(section.getByRole('cell',{name:'แว่นตานิรภัย สีใส',exact:true})).toBeVisible();
  const pairRow=section.locator('tbody tr').filter({has:page.getByRole('cell',{name:'คู่',exact:true})});
  await expect(pairRow.getByRole('cell',{name:'2,105',exact:true})).toBeVisible();
  await expect(pairRow.getByRole('cell',{name:'7',exact:true})).toBeVisible();
  let downloadPromise=page.waitForEvent('download');
  await section.getByRole('button',{name:'Export Excel '+dept,exact:true}).click();
  const download=await downloadPromise;
  const wb=new ExcelJS.Workbook();await wb.xlsx.readFile(await download.path());
  const sheet=wb.getWorksheet('ตามแผนก');
  expect(sheet.getCell('A2').value).toContain('2026-10 ถึง 2026-10');
  expect(sheet.getRow(20).values.join(' ')).not.toContain('รวมแยก');
  const dataRows=Array.from({length:15},(_,i)=>sheet.getRow(i+6).values.slice(1));
  expect(dataRows.reduce((n,r)=>n+r[4],0)).toBe(2132);
  expect(dataRows.reduce((n,r)=>n+r[5],0)).toBe(9);
  await section.getByRole('button',{name:/^สินค้า/}).click();
  await section.getByLabel('ค้นหาในรายงานการเบิก').fill('ถุงมือป้องกันการบาด');
  await section.getByRole('button',{name:/^ถุงมือป้องกันการบาด/}).click();
  await expect(section.locator('tbody tr')).toHaveCount(2);
  downloadPromise=page.waitForEvent('download');
  await section.getByRole('button',{name:'Export Excel ตามตัวกรอง'}).click();
  const filtered=await downloadPromise;
  const selected=new ExcelJS.Workbook();await selected.xlsx.readFile(await filtered.path());
  expect(selected.getWorksheet('ตามสินค้า').getCell('C6').value).toBe(dept);
  expect(selected.getWorksheet('ตามสินค้า').getCell('A3').value).toContain('ค้นหา: ถุงมือป้องกันการบาด');
  await page.setViewportSize({width:390,height:844});
  await section.scrollIntoViewIfNeeded();
  await expect(section.getByRole('cell',{name:dept,exact:true}).first()).toBeVisible();
  expect(await section.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/ppe-reports-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await section.getByLabel('ค้นหาในรายงานการเบิก').fill('ไม่พบรายการนี้');
  await expect(section.getByRole('button',{name:'Export Excel ตามตัวกรอง'})).toBeDisabled();
});
